/**
 * /mail 工具栏的统一动效规格（2026-10-05 用户定稿：「动画丝滑和谐、统一联动」）。
 *
 * **一条规则：工具栏里所有可见变化共用 300ms + 同一条 ease-out 曲线 + 同时开始/结束。**
 * 账号收窄（max-width + 字号）、写邮件收窄（gap + grid 轨道 + 文字淡出）、
 * 搜索框伸缩（图标 ↔ 输入框交叉淡化）、邮箱行折叠（height/opacity）——全在这条曲线上。
 * 新加任何过渡都不要再引入第二种时长或曲线。
 *
 * ⚠ 为什么「同一条曲线」是硬要求（不是审美偏好）：
 * 这些过渡的收放量彼此是**比例关系**（容器宽 ↔ 文本字号 / 透明度 / gap），只有进度函数
 * f(t) 完全相同时，「容器宽 − 内容宽」才逐帧恒定——账号的 2px 余量（TRIGGER_SPARE_PX）
 * 在任何一帧都恰好够用，两个方向都不会把文本裁出省略号。
 *   • 字号若比宽度**快**（曾用弹簧曲线）：展开方向会先长出全字号、而容器还差 2~3px →
 *     1 帧的 `...` 闪烁（2026-10-05 逐帧采样实锤：close 第 9 帧 acctMaxW 63.4 < 内容 64）；
 *   • 字号若比宽度**慢**：收起方向同理；
 *   • 宽度若用弹簧（overshoot 会冲过目标值）：更早裁出省略号（更早一轮的教训）。
 * ⇒ 尺寸 / 透明度 / 字号统一 ease-out（无过冲），是唯一能保证「永不出省略号」的写法。
 *
 * ⚠ **配合的例外：过渡进行中把「省略号」换成「纯裁切」**。账号邮箱行是块里最宽的一行——
 *   容器要到动画末尾才装得下它，中途必然被裁。带省略号时那段时间会闪「…」（看起来像
 *   坏数据）；纯裁切（`overflow-hidden`，去掉 `text-ellipsis`）的右缘随容器移动，读起来
 *   是擦除式揭示（wipe）。实现见 account-menu.tsx 的 `animating` 标记。
 */

/** 工具栏统一时长（ms）。类名侧一律写死 `duration-300`，改这里必须同步改类的写法。 */
export const TOOLBAR_MS = 300;

/** 工具栏唯一曲线：尺寸 / 透明度 / 字号都用它（见上方说明，不要新增第二条曲线） */
export const MOTION_SIZE = "duration-300 ease-out";

